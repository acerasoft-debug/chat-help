<h2>Prima la via diretta</h2>
<p>
  La maggior parte dei problemi si risolve con un'e-mail. Scriva a <?= $mail ?> indicando il numero
  d'ordine e una breve descrizione. Di norma rispondiamo entro un giorno lavorativo e al più tardi
  dopo sette giorni comunichiamo una decisione o un aggiornamento.
</p>

<h2>Reclami sui venditori</h2>
<p>
  In caso di problemi con un venditore terzo — merce non arrivata, condizioni difformi, rimborso non
  effettuato — mediamo e possiamo trattenere la quota del venditore finché la questione non è
  chiarita. Se non si giunge a una soluzione, rimborsiamo noi stessi nei casi indicati nelle
  <a href="<?= h(vr_url('legal/agb.php')) ?>#s10">clausole 10.3</a> e
  <a href="<?= h(vr_url('legal/agb.php')) ?>#s12">12.2</a> delle condizioni generali.
</p>

<h2>Segnalazione di contenuti illegali (art. 16 DSA)</h2>
<p>
  Chiunque può segnalarci offerte che ritiene illegali — ad esempio contraffazioni, violazioni di
  marchi o prodotti non ammessi. La preghiamo di indicare:
</p>
<ul>
  <li>l'indirizzo esatto (URL) dell'offerta,</li>
  <li>una motivazione del perché il contenuto sarebbe illegale,</li>
  <li>il Suo nome e un indirizzo e-mail (tranne per segnalazioni di reati contro le persone),</li>
  <li>una dichiarazione che le Sue indicazioni sono, per quanto a Sua conoscenza, esatte e complete.</li>
</ul>
<p>
  Invii le segnalazioni a <?= $mail ?> con oggetto «Segnalazione DSA». Confermiamo subito la
  ricezione, decidiamo con tempestività e diligenza e Le comunichiamo la decisione con la
  motivazione. I titolari di diritti che ci inviano ripetutamente segnalazioni fondate vengono
  trattati in via prioritaria (art. 22 DSA).
</p>

<h2>Se rimuoviamo un'offerta</h2>
<p>
  I venditori interessati vengono informati con motivazione di rimozione, sospensione o riduzione
  della visibilità (art. 17 DSA) e possono opporsi alla decisione via e-mail entro 14 giorni.
  L'opposizione è esaminata da una persona che non ha partecipato alla decisione originaria.
  Comunichiamo la decisione sull'opposizione con motivazione.
</p>
<p>
  In caso di segnalazioni manifestamente infondate o di offerte ripetutamente illegali sospendiamo
  l'elaborazione dopo un ragionevole preavviso o blocchiamo l'account (art. 23 DSA).
</p>

<h2>Risoluzione extragiudiziale delle controversie per i consumatori</h2>
<p>
  Non siamo obbligati né disposti a partecipare a procedure di risoluzione delle controversie
  dinanzi a un organismo di conciliazione per i consumatori ai sensi della legge tedesca sulla
  risoluzione delle controversie dei consumatori (VSBG). La Sua possibilità di agire in giudizio
  resta impregiudicata; così come il nostro impegno a chiarire prima ogni caso direttamente.
</p>
<p>
  Nota: la precedente piattaforma di risoluzione online delle controversie (piattaforma ODR) della
  Commissione europea è stata chiusa il 20 luglio 2025. Il relativo link è stato quindi rimosso. Per
  i casi transfrontalieri può rivolgersi al Centro europeo dei consumatori
  (<a href="https://www.evz.de" rel="noopener">evz.de</a>).
</p>

<h2>Foro competente e diritto applicabile</h2>
<p>
  Si applica il diritto tedesco. Per i consumatori valgono i fori di legge; restano salve le norme
  imperative a tutela dei consumatori dello Stato di residenza (art. 6 comma 2 regolamento Roma I).
</p>

