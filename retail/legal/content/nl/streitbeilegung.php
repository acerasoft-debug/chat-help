</p>

<h2>Als wij een aanbieding verwijderen</h2>
<p>
  Betrokken verkopers worden gemotiveerd geïnformeerd over verwijdering, blokkering of beperking van
  de zichtbaarheid (art. 17 DSA) en kunnen binnen 14 dagen per e-mail bezwaar maken tegen de
  beslissing. Het bezwaar wordt beoordeeld door een persoon die niet bij de oorspronkelijke
  beslissing betrokken was. De beslissing op het bezwaar delen wij gemotiveerd mee.
</p>
<p>
  Bij kennelijk ongegronde meldingen of herhaaldelijk onrechtmatige aanbiedingen schorten wij de
  behandeling na een redelijke voorafgaande waarschuwing op, respectievelijk blokkeren wij het
  account (art. 23 DSA).
</p>

