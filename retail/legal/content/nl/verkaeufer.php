<p>
  10.1 Zakelijke Verkopers verstrekken de volgens art. 30 DSA vereiste gegevens: naam, adres,
  telefoonnummer, e-mailadres, handelsregisternummer of vergelijkbare identificatie en
  btw-identificatienummer, voor zover aanwezig. De Exploitant controleert deze gegevens met
  redelijke middelen en mag de aanbieding tot opheldering offline halen.
</p>
<p>
  10.2 De Verkoper staat ervoor in dat zijn aanbiedingen voldoen aan de voorschriften inzake
  productveiligheid en etikettering en dat hij over de vereiste vergunningen beschikt.
</p>
<p>
  10.3 Meldingen van onrechtmatige inhoud worden behandeld volgens art. 16 DSA. Betrokken Verkopers
  worden gemotiveerd geïnformeerd over verwijderingen en kunnen bezwaar maken
