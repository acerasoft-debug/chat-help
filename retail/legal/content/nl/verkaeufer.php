<h2 id="v1">1. Onderwerp</h2>
<p>
  1.1 Deze voorwaarden regelen de verhouding tussen <?= h($co) ?> als exploitant van de marktplaats
  <?= h($brand) ?> en personen die via het platform goederen aanbieden („Verkopers”).
</p>
<p>
  1.2 De Exploitant stelt de verkoopruimte, de betalingsafwikkeling via Stripe en het bestelbeheer
  ter beschikking. De koopovereenkomst over de aangeboden goederen komt uitsluitend tot stand tussen
  de Verkoper en de koper; de Exploitant wordt geen partij bij de overeenkomst.
</p>
<p>
  1.3 De Exploitant is gerechtigd betalingen van kopers namens de Verkoper met bevrijdende werking
  in ontvangst te nemen en verklaringen van kopers over de koopovereenkomst (met name herroeping en
  meldingen van gebreken) voor de Verkoper in ontvangst te nemen en door te sturen.
</p>

<h2 id="v2">2. Verkopersaccount en registratie</h2>
<p>
  2.1 De registratie vindt online plaats. Gegevens moeten juist, volledig en actueel zijn.
  Wijzigingen — met name van bedrijfsnaam, adres, fiscaal nummer of verkoperstype — moeten
  onverwijld worden doorgegeven.
</p>
<p>
  2.2 Toegangsgegevens moeten geheim worden gehouden. De Verkoper is aansprakelijk voor handelingen
  die via zijn account worden verricht, voor zover hem een verwijt treft.
</p>
<p>
  2.3 Vóór de eerste activering van een aanbieding moet de verificatie bij Stripe (Stripe Connect)
  zijn afgerond. Zonder afgeronde verificatie kan geen uitbetaling plaatsvinden; aanbiedingen
  blijven in dat geval offline.
</p>

<h2 id="v3">3. Zakelijk of particulier</h2>
<p>
  3.1 Bij de registratie moet worden aangegeven of als ondernemer („Handelaar”) of als privépersoon
  („Particuliere verkoper”) wordt verkocht. Deze vermelding wordt aan kopers getoond op de
  productpagina en tijdens het bestelproces en bepaalt welke consumentenrechten gelden.
</p>
<p>
  3.2 Wie planmatig, herhaaldelijk en met winstoogmerk verkoopt, handelt bedrijfsmatig — ongeacht
  de eigen inschatting. De juiste kwalificatie en alle fiscale, bedrijfs- en handelsrechtelijke
  verplichtingen vallen onder de verantwoordelijkheid van de Verkoper.
</p>
<p>
  3.3 De Exploitant is gerechtigd een account na voorafgaande aankondiging om te zetten naar
  „Handelaar” of te blokkeren wanneer de feitelijke verkoopactiviteit een bedrijfsmatig karakter
  heeft. Maatstaf zijn met name het aantal aanbiedingen, de omzet en de regelmaat.
</p>
<p>
  3.4 Handelaren zijn verplicht consumenten het wettelijke herroepingsrecht te verlenen, correcte
  facturen uit te reiken en de wettelijke garantie na te komen.
</p>

<h2 id="v4">4. Aanbiedingen en controle</h2>
<p>
  4.1 Aanbiedingen moeten juist, volledig en actueel zijn: merk, modelnaam, maat, staat, prijs
  inclusief btw en ten minste één eigen, onbewerkte afbeelding van de daadwerkelijk aanwezige
  goederen.
</p>
<p>
  4.2 Bij gebruikte goederen moeten gebruikssporen worden beschreven. Ontbrekende of verfraaiende
  gegevens komen voor rekening van de Verkoper.
</p>
<p>
  4.3 Elke nieuwe of gewijzigde aanbieding wordt vóór activering gecontroleerd. De controle omvat
  plausibiliteit, beeldkwaliteit en prijs; de Exploitant kan herkomstbewijzen (aankoopbewijzen)
  verlangen. Er bestaat geen recht op activering.
</p>
<p>
  4.4 De Verkoper bewaart aankoopbewijzen ten minste gedurende de looptijd van de aanbieding plus
  twee jaar en overlegt ze op verzoek binnen vijf werkdagen.
</p>
<p>
  4.5 De Verkoper zorgt ervoor dat aangeboden goederen beschikbaar zijn. Herhaalde niet-levering na
  verkoop geeft de Exploitant het recht het account te blokkeren.
</p>

<h2 id="v5">5. Verboden goederen</h2>
<p>Niet aangeboden mogen worden, in het bijzonder:</p>
<ul>
  <li>vervalsingen, replica's, „dupes” en goederen waarvan kenmerken zijn verwijderd of gewijzigd;</li>
  <li>goederen zonder traceerbare herkomst of uit onrechtmatige bron;</li>
  <li>goederen die voor het eerst buiten de EER in de handel zijn gebracht, tenzij de merkhouder met
      de doorverkoop binnen de EER heeft ingestemd;</li>
  <li>monsters zonder verkoopvrijgave („not for resale”), personeelsartikelen met een
      doorverkoopverbod;</li>
  <li>goederen die in strijd zijn met voorschriften inzake productveiligheid, etikettering of
      textieletikettering;</li>
  <li>bont en exotisch leer zonder de vereiste documenten (CITES).</li>
</ul>
<p>
  Overtredingen leiden tot onmiddellijke verwijdering van de aanbieding en in de regel tot
  opzegging van het verkopersaccount.
</p>

