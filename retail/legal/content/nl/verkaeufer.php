<h2 id="v12">12. Blokkering en opzegging</h2>
<p>
  12.1 Beide partijen kunnen de verkopersrelatie te allen tijde in tekstvorm opzeggen met een
  termijn van 14 dagen. Lopende bestellingen moeten nog volledig worden afgewikkeld.
</p>
<p>
  12.2 De Exploitant kan aanbiedingen onmiddellijk verwijderen en het account blokkeren bij
  overtreding van artikel 5, bij onjuiste opgave van de verkopersstatus, bij herhaalde
  niet-levering of bij een gegrond vermoeden van vervalsingen. De blokkering wordt gemotiveerd.
</p>
<p>
  12.3 Na beëindiging worden verschuldigde uitbetalingen na afloop van de retour- en
  terugboekingstermijnen, uiterlijk 90 dagen na de laatste bestelling, in opdracht gegeven.
</p>

