<h2 id="v7">7. Betaling en uitbetaling</h2>
<p>
  7.1 De betalingsafwikkeling verloopt via Stripe. De Verkoper sluit hiervoor een eigen overeenkomst
  met Stripe (Stripe Connected Account Agreement) en aanvaardt de voorwaarden daarvan.
</p>
<p>
  7.2 Afhankelijk van de samenstelling van de bestelling wordt ofwel rechtstreeks aan het account
  van de Verkoper uitbetaald (betaling met doorbetaling), ofwel wordt het bedrag eerst op de
  platformrekening ontvangen en vervolgens als afzonderlijke overboeking aan de Verkoper
  overgemaakt. In beide gevallen ontvangt de Verkoper de brutoverkoopprijs van zijn artikelen
  verminderd met de commissie.
</p>
<p>
  7.3 Het uitbetalingsritme naar de bankrekening volgt de regels van Stripe. De Exploitant bewaart
  geen klantgelden en is geen rente verschuldigd.
</p>
<p>
  7.4 Is de Stripe-verificatie nog niet afgerond, dan blijft het verkopersaandeel tot de afronding
  van de verificatie op de platformrekening staan. Wordt de verificatie niet binnen 180 dagen
  afgerond, dan kan de Exploitant de betrokken bestellingen annuleren en de kopers terugbetalen.
</p>
<p>
  7.5 De Exploitant mag uitbetalingen inhouden of verrekenen voor zover er gegronde vorderingen op
  de Verkoper bestaan — met name uit terugbetalingen aan kopers, terugboekingen (chargebacks) of
  overtredingen van artikel 5. De inhouding wordt gemotiveerd en is beperkt tot de hoogte van de
  vorderingen.
</p>

<h2 id="v8">8. Verzending en retouren</h2>
<p>
  8.1 De Verkoper verzendt binnen twee werkdagen na ontvangst van de betaling, verzekerd en met
  track &amp; trace, en voert de verzendgegevens onverwijld in.
</p>
<p>
  8.2 Retouren neemt de Verkoper terug op het door hem opgegeven adres. Handelaren betalen
  herroepingen tijdig terug; blijft terugbetaling uit, dan is de Exploitant gerechtigd de koper
  terug te betalen en het bedrag te verrekenen met uitbetalingen aan de Verkoper.
</p>
<p>
  8.3 Bij particuliere verkopers bestaat geen wettelijk herroepingsrecht. Wijken de goederen echter
  wezenlijk af van de beschrijving of zijn ze geen origineel, dan is de Verkoper verplicht ze terug
  te nemen en terug te betalen.
</p>

<h2 id="v9">9. Premium Outlet</h2>
<p>
  9.1 De Verkoper kan goederen ter beschikking stellen voor de Vault. Openingsprijs, minimumprijs en
  verlagingsschema worden vóór de opening overeengekomen en daarna niet meer gewijzigd.
</p>
<p>
  9.2 De Verkoper erkent dat de verkoop tot stand kan komen tegen elke prijs tussen de openingsprijs
  en de minimumprijs, en dat intrekking van de deelname na opening van het kavel niet mogelijk is
  zolang het kavel loopt.
</p>
<p>
  9.3 De minimumprijs wordt nooit onderschreden. Wordt een kavel tot het einde niet verkocht, dan
  wordt het gesloten en kan het opnieuw op de gebruikelijke wijze worden aangeboden.
</p>

