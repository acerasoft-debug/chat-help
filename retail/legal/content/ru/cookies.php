<h2>Cookie от Stripe</h2>
<p>
  При оплате Вы переходите на страницу Stripe. Там Stripe устанавливает собственные cookie,
  необходимые для обработки платежа и предотвращения мошенничества. Это происходит на домене Stripe и
  регулируется <a href="https://stripe.com/privacy" rel="noopener">политикой конфиденциальности
  Stripe</a>. На наших страницах скрипт Stripe не подключается.
</p>

<h2>Без локального хранилища, без отпечатков</h2>
<p>
  Мы не используем ни <code>localStorage</code>, ни <code>sessionStorage</code>, ни пиксели, ни
  техники fingerprinting, ни кросс-девайсное распознавание. Все шрифты, стили, скрипты и изображения
  размещены на нашем сервере; при открытии страницы соединение с третьими лицами не устанавливается.
</p>

<h2>Удаление или блокировка cookie</h2>
<p>
  Вы можете в любое время удалить или заблокировать cookie в настройках браузера. Если
  заблокировать сессионный cookie, корзина, оформление заказа и вход продавца перестанут работать —
  исчезнет техническая нить, связывающая Ваши шаги. Язык и доступ к Vault можно блокировать без
  проблем; тогда мы снова спросим язык, а ранний доступ будет недоступен.
</p>
