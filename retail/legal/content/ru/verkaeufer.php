<h2 id="v7">7. Оплата и выплата</h2>
<p>
  7.1 Платежи обрабатываются через Stripe. Для этого Продавец заключает собственный договор со Stripe
  (Stripe Connected Account Agreement) и принимает его условия.
</p>
<p>
  7.2 В зависимости от состава заказа оплата либо поступает непосредственно на счёт Продавца (платёж с
  перенаправлением), либо сначала зачисляется на счёт платформы, а затем переводится Продавцу
  отдельным переводом. В обоих случаях Продавец получает валовую цену продажи своих товаров за вычетом
  комиссии.
</p>
<p>
  7.3 Периодичность выплат на банковский счёт определяется правилами Stripe. Оператор не хранит
  средства клиентов и проценты не выплачивает.
</p>
<p>
  7.4 Если проверка в Stripe ещё не завершена, доля Продавца остаётся на счёте платформы до её
  завершения. Если проверка не завершена в течение 180 дней, Оператор может отменить соответствующие
  заказы и вернуть деньги покупателям.
</p>
<p>
  7.5 Оператор вправе удерживать выплаты или производить зачёт в той мере, в какой к Продавцу имеются
  обоснованные требования — в частности, из возвратов покупателям, чарджбэков или нарушений п. 5.
  Удержание обосновывается и ограничивается суммой требований.
</p>

