<h2>Как проходит оплата</h2>
<p>
  Вы добавляете товары в корзину, выбираете при оформлении страну доставки и подтверждаете условия
  продажи и информацию о праве на отказ. Для оплаты мы перенаправляем Вас к нашему платёжному
  провайдеру Stripe. Там Вы вводите платёжные данные и завершаете оплату; затем возвращаетесь к
  подтверждению заказа.
</p>
<p>
  <strong>Данные Вашей карты никогда не попадают на наши серверы.</strong> От Stripe мы получаем
  лишь сведения о том, прошёл ли платёж, сумму, способ оплаты в общем виде и данные, необходимые
  для доставки и счёта.
</p>

