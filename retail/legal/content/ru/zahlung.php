<h2>Срок оплаты</h2>
<p>
  Покупная цена подлежит уплате с момента заключения договора. При способах оплаты с отложенным
  расчётом мы резервируем Ваши товары и отправляем после подтверждения платежа.
</p>

<h2>Валюта и налог</h2>
<p>
  Все цены указаны в евро и включают установленный законом НДС в размере
  <?= h((int)vr_config('vat_rate_bps', 1900) / 100) ?> %, если соответствующий продавец является
  плательщиком НДС. Для товаров частных продавцов НДС не выделяется. Если Ваш банк производит
  расчёт в другой валюте, он может взимать комиссию за конвертацию — на это мы не влияем.
</p>

<h2>Счёт</h2>
<p>
  Счёт Вы получаете вместе с товаром или по эл. почте. Для товаров коммерческих сторонних
  продавцов счёт выставляет соответствующий торговец; для собственных товаров —
  <?= h((string)(vr_config('company')['legal_name'] ?? '')) ?>. Частные продавцы не выставляют
  счёт с выделением НДС.
</p>

<h2>Возврат средств</h2>
<p>
  Возврат средств всегда производится на то же платёжное средство, которым Вы оплачивали. При
  Klarna возврат проходит через Ваш аккаунт Klarna, при SEPA — на списанный счёт. Мы начинаем
  обработку после получения и проверки возврата; до зачисления в Вашем банке в зависимости от
  способа оплаты может пройти несколько рабочих дней.
</p>

<h2>Неудачный платёж</h2>
<p>
  Если платёж отклонён, договор не заключается и ничего не списывается. Ваша корзина сохраняется,
  чтобы Вы могли попробовать снова или выбрать другой способ оплаты. Самая частая причина —
  незавершённое подтверждение 3-D Secure.
</p>

<h2>Безопасность платежей</h2>
<p>
  Соединение полностью зашифровано по TLS. Stripe сертифицирован как платёжный провайдер по PCI DSS
  уровня 1 и лицензирован в Европе как платёжное учреждение (Stripe Payments Europe, Limited,
  Дублин). Для предотвращения мошенничества Stripe автоматически проверяет транзакции; мы не храним
  номера карт.
</p>
