<h2>Наша цель</h2>
<p>
  Мы хотим, чтобы этим магазином мог пользоваться каждый — с клавиатурой, с программой экранного
  доступа, с увеличенным шрифтом, с уменьшенной анимацией. Основой служат требования немецкого
  закона об усилении доступности (BFSG) и стандарт EN 301 549, ссылающийся на WCAG 2.1 уровня AA.
</p>

<h2>Состояние реализации</h2>
<p>
  По нашей оценке этот сайт <strong>в значительной степени соответствует</strong> WCAG 2.1 уровня
  AA. Оценка основана на внутренней проверке, а не на внешнем аудите.
</p>

<h3>Что реализовано</h3>
<ul>
  <li><strong>Работает без JavaScript:</strong> навигация, фильтры, корзина, оформление заказа и
      раздел продавца полностью работают на чистых HTML-формах. JavaScript добавляет лишь удобство
      (обратный отсчёт, переключатель количества, плавные появления).</li>
  <li><strong>Управление с клавиатуры:</strong> все интерактивные элементы достижимы, с видимой
      рамкой фокуса; ссылка «Перейти к содержимому» расположена в начале страницы.</li>
  <li><strong>Контраст:</strong> каждый текстовый узел на основных страницах измерен автоматически
      (фактически отрисованный цвет на фактически отрисованном фоне, включая прозрачность). Все
      достигают минимум 4,5:1, крупный текст — минимум 3:1. Тёмная зона Vault использует собственные
      значения серого, а акцентные цвета имеют более тёмный текстовый вариант на светлом фоне.</li>
  <li><strong>Структура:</strong> один H1 на страницу, логичные уровни заголовков, ориентиры
      (<code>header</code>, <code>nav</code>, <code>main</code>, <code>footer</code>), подписанные
      поля форм, связанные сообщения об ошибках.</li>
  <li><strong>Изображения:</strong> изображения товаров содержат альтернативный текст из бренда и
      названия; чисто декоративная графика скрыта от вспомогательных технологий.</li>
  <li><strong>Движение:</strong> при включённой системной настройке «Уменьшить движение» бегущая
      строка, появления и переходы отключаются.</li>
  <li><strong>Масштабирование и малые экраны:</strong> макет остаётся пригодным до 400 % увеличения
      без горизонтальной прокрутки содержимого страницы.</li>
  <li><strong>Язык:</strong> язык страницы указан в HTML и переключается через селектор языка
      (десять языков).</li>
  <li><strong>Галерея изображений:</strong> каждое изображение товара — обычная ссылка на файл
      изображения. Без JavaScript оно открывается напрямую; с JavaScript — в лайтбоксе, который
      закрывается клавишей Esc и листается стрелками.</li>
  <li><strong>Поисковые подсказки:</strong> управляются стрелками и Enter, закрываются Esc. Само поле
      поиска работает и без подсказок как обычная форма.</li>
  <li><strong>Избранное:</strong> реализовано как форма; состояние хранится в
      <code>aria-pressed</code> и корректно сохраняется и без JavaScript.</li>
</ul>

<h3>Известные ограничения</h3>
<ul>
  <li><strong>Изображения товаров сторонних продавцов:</strong> альтернативные тексты формируются
      автоматически из бренда и названия. Они не описывают изображение детально — при вопросах о
      товаре мы с удовольствием опишем его по эл. почте.</li>
  <li><strong>Страница оплаты:</strong> оплата проходит в Stripe. За доступность этих страниц
      отвечает Stripe; нам не известны недостатки соответствия, но мы не проверяли их сами.</li>
  <li><strong>Обратный отсчёт Vault:</strong> оставшееся время обновляется ежесекундно. Определяющая
      цена указана рядом текстом и меняется только после загрузки страницы, так что работа
      программы экранного доступа не нарушается живыми изменениями.</li>
  <li><strong>PDF-документы:</strong> счета и этикетки возврата частично формируются продавцами и
      перевозчиками и могут быть без тегов. По запросу мы предоставляем содержимое в доступной
      форме.</li>
</ul>

